#!/usr/bin/env python3
"""
The game box's sound bank (P768), made on the Mac:

    python3 tools/sound_bank.py            # writes games/box_bank.raw, box_bank.py and box_bank.SOURCES.md
    python3 tools/sound_bank.py --wav DIR  # also one WAV file per sound in DIR, to hear them on the Mac,
                                           # and theme_a.wav and theme_b.wav, the two music candidates

Each short sound is generated here, from soft sine notes or filtered noise. The music is a loop from a note list
(theme). The fire loop comes from games/fire16k.wav (CC0), and Rescue's shouts are cut from games/help16k.wav (CC0).
box_bank.SOURCES.md names the source and the license of each sound.
The bank is 16 kHz mono int16, little-endian. The index gives each sound's first sample and its length.
--- MVP (P768) ---
"""

import math
import os
import struct
import sys
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATE = 16000
ATTACK = 160  # samples of a smooth rise, 10 ms, so a sound starts soft and does not click


def note(ms, hz_from, hz_to, peak):
    """A soft sine note: it glides from hz_from to hz_to, rises smoothly, and fades to nothing at its end."""
    n, phase, out = RATE * ms // 1000, 0.0, []
    for i in range(n):
        k = i / n
        phase += 2 * math.pi * (hz_from + (hz_to - hz_from) * k) / RATE
        rise = 0.5 - 0.5 * math.cos(math.pi * min(1.0, i / ATTACK))
        out.append(int(peak * rise * (1 - k) ** 2 * math.sin(phase)))
    return out


HZ = {name + str(octave): 440 * 2 ** ((12 * (octave - 4) + k - 9) / 12)
      for octave in (3, 4, 5, 6) for k, name in enumerate("C . D . E F . G . A . B".split()) if name != "."}


def theme(melody, bass, step_ms, ring_ms, peak):
    """A music loop from a note list, like a small music box. `melody` has one note name per step ("-" is a rest),
    and `bass` one per 4 steps. Each note is a plucked sine with a little of its octave, and it rings for ring_ms,
    also round the loop's end into its start, so the loop has no seam."""
    step, ring = RATE * step_ms // 1000, RATE * ring_ms // 1000
    n = step * len(melody.split())
    out = [0.0] * n

    def pluck(first, hz, level, length):
        for i in range(length):
            k = i / length
            rise = 0.5 - 0.5 * math.cos(math.pi * min(1.0, i / ATTACK))
            w = 2 * math.pi * hz * i / RATE
            out[(first + i) % n] += level * rise * (1 - k) ** 3 * (math.sin(w) + 0.25 * math.sin(2 * w))

    for i, name in enumerate(melody.split()):
        if name != "-":
            pluck(i * step, HZ[name], 1.0, ring)
    for i, name in enumerate(bass.split()):
        pluck(4 * i * step, HZ[name], 0.6, 4 * step)
    top = max(abs(x) for x in out)
    return [int(x * peak / top) for x in out]


