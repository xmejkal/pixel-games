MUSIC = "a"

FIRE_WAV = os.path.join(ROOT, "games", "fire16k.wav")
FIRE_SOURCE = open(os.path.join(ROOT, "games", "fire16k.SOURCE.txt")).read().strip()
OURS = "generated by tools/sound_bank.py (this repository's own code, soft sine notes)"


def fire_loop(path, ms, blend_ms, peak, smooth):
    """A loop of the recording with no seam: its first `ms`, with the next `blend_ms` faded over its start, so the
    loop's end runs into its start. `smooth` (0 to 1) is a low-pass that takes the sharp edge off the crackle."""
    with wave.open(path, "rb") as w:
        assert (w.getnchannels(), w.getsampwidth(), w.getframerate()) == (1, 2, RATE), path
        data = struct.unpack("<%dh" % w.getnframes(), w.readframes(w.getnframes()))
    n, blend = RATE * ms // 1000, RATE * blend_ms // 1000
    assert n + blend <= len(data), "the recording is shorter than the loop and its blend"
    out, low = [], 0.0
    for i in range(n):
        x = data[i]
        if i < blend:  # equal power: the tail after the loop's end fades out as the start fades in
            k = i / blend
            x = data[i] * math.sin(k * math.pi / 2) + data[n + i] * math.cos(k * math.pi / 2)
        out.append(x)
    for _ in range(2):  # twice round the loop, so the filter's state at the seam is the loop's own
        for i in range(n):
            low += (1 - smooth) * (out[i] - low)
            out[i] = low
    top = max(abs(x) for x in out)
    return [int(x * peak / top) for x in out]


# --- MVP (P800) --- Rescue's sounds: the hose, the siren, the meteor's whoosh and boom, the cheer, and two shouts
HELP_WAV = os.path.join(ROOT, "games", "help16k.wav")
HELP_SOURCE = open(os.path.join(ROOT, "games", "help16k.SOURCE.txt")).read().strip()
HELP_CUT = (1.56, 2.02)  # s: the one-word "Help!" in the clip, its second phrase
CHILD_PITCH = 1.35  # the child's shout: the same word played this much faster, so higher (about five semitones)
NOISE_OURS = "generated by tools/sound_bank.py (this repository's own code, filtered noise)"


def noise(n, seed):
    """n samples of white noise, -1 to 1, from a small LCG: the same every run."""
    out, x = [], seed
    for _ in range(n):
        x = (1103515245 * x + 12345) & 0x7FFFFFFF
        out.append(x / 0x3FFFFFFF - 1.0)
    return out


def scaled(out, peak):
    top = max(abs(v) for v in out) or 1.0
    return [int(v * peak / top) for v in out]


def hose(ms, peak):
    """The hose: a hiss that loops with no seam. White noise band-passed (a fast low-pass less a slow one), each
    filter run twice round the loop so its state at the seam is the loop's own, with a slow flutter of whole cycles."""
    n = RATE * ms // 1000
    raw, fast, slow = noise(n, 800), 0.0, 0.0
    out = [0.0] * n
    for _ in range(2):
        for i in range(n):
            fast += 0.55 * (raw[i] - fast)
            slow += 0.06 * (raw[i] - slow)
            out[i] = fast - slow
    flutter = 8  # cycles over the loop
    return scaled([v * (0.85 + 0.15 * math.sin(2 * math.pi * flutter * i / n)) for i, v in enumerate(out)], peak)


def tone(ms, hz, peak):
    """A held sine with a little of its octave, a smooth rise and fall at both ends (no click)."""
    n, out = RATE * ms // 1000, []
    for i in range(n):
        edge = min(1.0, i / ATTACK, (n - i) / ATTACK)
        w = 2 * math.pi * hz * i / RATE
        out.append(int(peak * edge * (math.sin(w) + 0.2 * math.sin(2 * w)) / 1.2))
    return out


def siren(peak):
    """The fire engine's two tones, twice: high, low, high, low, 0.8 s."""
    return tone(200, 932, peak) + tone(200, 698, peak) + tone(200, 932, peak) + tone(200, 698, peak)


def whoosh(ms, peak):
    """A meteor coming: noise low-passed ever lower as it falls, rising, then cut off at the impact."""
    n = RATE * ms // 1000
    raw, low, out = noise(n, 801), 0.0, []
    for i in range(n):
        k = i / n
        low += (0.5 - 0.42 * k) * (raw[i] - low)
        out.append(low * min(1.0, k * 1.6) * min(1.0, (n - i) / ATTACK))
    return scaled(out, peak)


def boom(ms, peak):
    """The impact: a low sine falling from 110 to 38 Hz under a burst of low noise, fading out."""
    n = RATE * ms // 1000
    raw, low, phase, out = noise(n, 802), 0.0, 0.0, []
    for i in range(n):
        k = i / n
        phase += 2 * math.pi * (110 - 72 * k) / RATE
        low += 0.08 * (raw[i] - low)
        rise = min(1.0, i / 40)
        out.append(rise * ((1 - k) ** 2 * math.sin(phase) + 2.2 * (1 - k) ** 4 * low))
    return scaled(out, peak)


def cheer(peak):
    """A saved person: a small rising jingle, C E G and the high C rung out."""
    return note(90, 523, 523, peak) + note(90, 659, 659, peak) + note(90, 784, 784, peak) + note(260, 1047, 1047, peak)


def shout(path, cut, rate, peak):
    """A word cut from a recording at cut (s, s), faded 10 ms at both ends; rate above 1 plays it faster and higher
    (linear resampling, our own)."""
    with wave.open(path, "rb") as w:
        assert (w.getnchannels(), w.getsampwidth(), w.getframerate()) == (1, 2, RATE), path
        data = struct.unpack("<%dh" % w.getnframes(), w.readframes(w.getnframes()))
    word = data[int(cut[0] * RATE):int(cut[1] * RATE)]
    n = int(len(word) / rate)
    out = []
    for i in range(n):
        t = i * rate
        k = int(t)
        a, b = word[k], word[min(k + 1, len(word) - 1)]
        fade = min(1.0, i / ATTACK, (n - 1 - i) / ATTACK)
        out.append((a + (b - a) * (t - k)) * fade)
    return scaled(out, peak)


