#!/usr/bin/env python3
"""
The game box's sound bank (P768), made on the Mac:

    python3 tools/sound_bank.py            # writes games/box_bank.raw, box_bank.py and box_bank.SOURCES.md
    python3 tools/sound_bank.py --wav DIR  # also one WAV file per sound in DIR, to hear them on the Mac,
                                           # and theme_a.wav and theme_b.wav, the two music candidates

Each short sound is generated here, from soft sine notes. The music is a loop from a note list (theme). The fire loop comes from games/fire16k.wav (CC0).
box_bank.SOURCES.md names the source and the license of each sound.
The bank is 16 kHz mono int16, little-endian. The index gives each sound's first sample and its length.
--- MVP (P768) ---
"""

import math
import os
import struct
import sys
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATE = 16000
ATTACK = 160  # samples of a smooth rise, 10 ms, so a sound starts soft and does not click


def note(ms, hz_from, hz_to, peak):
    """A soft sine note: it glides from hz_from to hz_to, rises smoothly, and fades to nothing at its end."""
    n, phase, out = RATE * ms // 1000, 0.0, []
    for i in range(n):
        k = i / n
        phase += 2 * math.pi * (hz_from + (hz_to - hz_from) * k) / RATE
        rise = 0.5 - 0.5 * math.cos(math.pi * min(1.0, i / ATTACK))
        out.append(int(peak * rise * (1 - k) ** 2 * math.sin(phase)))
    return out


HZ = {name + str(octave): 440 * 2 ** ((12 * (octave - 4) + k - 9) / 12)
      for octave in (3, 4, 5, 6) for k, name in enumerate("C . D . E F . G . A . B".split()) if name != "."}


def theme(melody, bass, step_ms, ring_ms, peak):
    """A music loop from a note list, like a small music box. `melody` has one note name per step ("-" is a rest),
    and `bass` one per 4 steps. Each note is a plucked sine with a little of its octave, and it rings for ring_ms,
    also round the loop's end into its start, so the loop has no seam."""
    step, ring = RATE * step_ms // 1000, RATE * ring_ms // 1000
    n = step * len(melody.split())
    out = [0.0] * n

    def pluck(first, hz, level, length):
        for i in range(length):
            k = i / length
            rise = 0.5 - 0.5 * math.cos(math.pi * min(1.0, i / ATTACK))
            w = 2 * math.pi * hz * i / RATE
            out[(first + i) % n] += level * rise * (1 - k) ** 3 * (math.sin(w) + 0.25 * math.sin(2 * w))

    for i, name in enumerate(melody.split()):
        if name != "-":
            pluck(i * step, HZ[name], 1.0, ring)
    for i, name in enumerate(bass.split()):
        pluck(4 * i * step, HZ[name], 0.6, 4 * step)
    top = max(abs(x) for x in out)
    return [int(x * peak / top) for x in out]


# The PO, 2026-11-11: "at least basi background music, that should be everywhere, nice cute simple.. be creative".
# Two candidates, both ours. `--wav DIR` writes both, and MUSIC names the one in the bank.
THEMES = {
    "a": theme("E5 G5 A5 G5 E5 - C5 - D5 E5 G5 E5 D5 - - - E5 G5 A5 C6 A5 - G5 - E5 D5 C5 D5 C5 - - -",
               "C4 C4 G3 G3 A3 C4 G3 C4", 180, 540, 1600),  # a slow music box, 5.76 s
    "b": theme("C5 E5 G5 E5 C6 - G5 - A4 C5 E5 C5 A5 - E5 - F4 A4 C5 A4 F5 - C5 - G4 B4 D5 G5 B5 - G5 -",
               "C4 C4 A3 A3 F3 F3 G3 G3", 150, 450, 1600),  # a bouncy arpeggio, 4.8 s
}
MUSIC = "a"

FIRE_WAV = os.path.join(ROOT, "games", "fire16k.wav")
FIRE_SOURCE = open(os.path.join(ROOT, "games", "fire16k.SOURCE.txt")).read().strip()
OURS = "generated by tools/sound_bank.py (this repository's own code, soft sine notes)"


def fire_loop(path, ms, blend_ms, peak, smooth):
    """A loop of the recording with no seam: its first `ms`, with the next `blend_ms` faded over its start, so the
    loop's end runs into its start. `smooth` (0 to 1) is a low-pass that takes the sharp edge off the crackle."""
    with wave.open(path, "rb") as w:
        assert (w.getnchannels(), w.getsampwidth(), w.getframerate()) == (1, 2, RATE), path
        data = struct.unpack("<%dh" % w.getnframes(), w.readframes(w.getnframes()))
    n, blend = RATE * ms // 1000, RATE * blend_ms // 1000
    assert n + blend <= len(data), "the recording is shorter than the loop and its blend"
    out, low = [], 0.0
    for i in range(n):
        x = data[i]
        if i < blend:  # equal power: the tail after the loop's end fades out as the start fades in
            k = i / blend
            x = data[i] * math.sin(k * math.pi / 2) + data[n + i] * math.cos(k * math.pi / 2)
        out.append(x)
    for _ in range(2):  # twice round the loop, so the filter's state at the seam is the loop's own
        for i in range(n):
            low += (1 - smooth) * (out[i] - low)
            out[i] = low
    top = max(abs(x) for x in out)
    return [int(x * peak / top) for x in out]


# The PO, 2026-11-11: "the sounds should be nice and not aggressive". So: pure sines, no noise, low peaks (of 32767).
# name, samples, source and license
SOUNDS = (
    ("jump", note(120, 440, 660, 3000), OURS),  # a small rising "boop"
    ("land", note(80, 190, 110, 2600), OURS),  # a low soft thump
    ("pickup", note(70, 880, 880, 2200) + note(150, 1319, 1319, 2200), OURS),  # two bright notes up
    ("footstep", note(40, 230, 150, 1000), OURS),  # a quiet tap
    ("die", note(140, 659, 659, 3200) + note(140, 523, 523, 3200) + note(320, 392, 370, 3200), OURS),  # three notes down
    ("fire", fire_loop(FIRE_WAV, 2400, 400, 4500, 0.55), FIRE_SOURCE + " Cut to a 2.4 s loop, blended at its seam, "
     "low-passed and made quieter by tools/sound_bank.py."),
    ("music", THEMES[MUSIC], "generated by tools/sound_bank.py from this repository's own note list (theme %s)" % MUSIC),
)


def main(argv):
    index, at = [], 0
    with open(os.path.join(ROOT, "games", "box_bank.raw"), "wb") as f:
        for name, samples, _ in SOUNDS:
            f.write(struct.pack("<%dh" % len(samples), *samples))
            index.append('    "%s": (%d, %d),' % (name, at, len(samples)))
            at += len(samples)
    with open(os.path.join(ROOT, "games", "box_bank.py"), "w") as f:
        f.write("# Written by tools/sound_bank.py. Regenerate it; do not edit it.\n"
                "# name: (first sample, samples) in box_bank.raw, 16 kHz mono int16\n"
                "BOX_BANK_INDEX = {\n%s\n}\n" % "\n".join(index))
    with open(os.path.join(ROOT, "games", "box_bank.SOURCES.md"), "w") as f:
        f.write("# The sounds of games/box_bank.raw and where each comes from\n\n"
                "Written by tools/sound_bank.py. Regenerate it; do not edit it.\n\n"
                "| Sound | Samples | Source and license |\n|---|---|---|\n")
        for name, samples, source in SOUNDS:
            f.write("| `%s` | %d | %s |\n" % (name, len(samples), source))
    if len(argv) == 2 and argv[0] == "--wav":
        files = [(name, samples) for name, samples, _ in SOUNDS] + [("theme_" + k, v) for k, v in THEMES.items()]
        for name, samples in files:
            with wave.open(os.path.join(argv[1], name + ".wav"), "wb") as w:
                w.setnchannels(1)
                w.setsampwidth(2)
                w.setframerate(RATE)
                w.writeframes(struct.pack("<%dh" % len(samples), *samples))
    print("box_bank.raw: %d sounds, %d samples, %d bytes" % (len(SOUNDS), at, 2 * at))


if __name__ == "__main__":
    main(sys.argv[1:])
