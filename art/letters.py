ADVANCE = 6  # grid steps from one letter to the next: 5 for the letter, 1 between


def text_width(words, unit):
    """The width of words in px: the last letter has no gap after it."""
    return (len(words) * ADVANCE - 2) * unit


def write(img, words, x, y, unit, width, fill=255):
    """Stroke words into img (a mask or a picture), the top left of the first letter at (x, y) px, unit px per grid
    step, each stroke width px wide with round ends."""
    d = ImageDraw.Draw(img)
    r = width / 2
    for k, ch in enumerate(words):
        left = x + k * ADVANCE * unit
        for line in GLYPHS[ch]:
            pts = [(left + gx * unit, y + gy * unit) for gx, gy in line]
            if len(set(pts)) > 1:
                d.line(pts, fill=fill, width=max(1, round(width)), joint="curve")
            for px, py in pts:  # the round ends, and a dot on its own
                d.ellipse((px - r, py - r, px + r, py + r), fill=fill)
